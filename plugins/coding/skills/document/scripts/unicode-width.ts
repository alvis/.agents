/**
 * looks up the terminal column width of one Unicode code point
 * @param codePoint scalar value to classify
 * @returns 0 for combining and zero-width ranges, 2 for East Asian wide ranges, otherwise 1
 */
export function getCodePointWidth(codePoint: number): 0 | 1 | 2 {
  let lower = 0;
  let upper = NON_STANDARD_WIDTH_RANGES.length - 1;
  while (lower <= upper) {
    const middle = Math.floor((lower + upper) / 2);
    const [start, end, width] = NON_STANDARD_WIDTH_RANGES[middle]!;
    if (codePoint < start) upper = middle - 1;
    else if (codePoint > end) lower = middle + 1;
    else return width;
  }
  return 1;
}
